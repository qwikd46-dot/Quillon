    def test_searxng_lifecycle_contract(self):
        checkup_path = ROOT / "bfsb_checkup.sh"
        checkup = checkup_path.read_text(encoding="utf-8")
        self.assertTrue(os.access(checkup_path, os.X_OK))
        self.assertIn("REPLACE_EXISTING", checkup)
        self.assertIn("cleanup_stale_searxng", checkup)
        self.assertIn("owner_is_active", checkup)
        self.assertNotIn("pkill -KILL", checkup)
        self.assertNotIn("pkill -TERM -f", checkup)
        self.assertIn("BFSB_BROWSER_PID_FILE", checkup)
        self.assertIn("stop_recorded_process", checkup)
        self.assertNotIn("stop_sarxng", checkup)
        self.assertIn("exit 0", checkup)
        for filename in ("bfsb_launcher.sh", "bfsb_launcher.podman.sh"):
            launcher_path = ROOT / filename
            launcher = launcher_path.read_text(encoding="utf-8")
            self.assertTrue(os.access(launcher_path, os.X_OK))
            self.assertIn('"$BFSB_CHECKUP" --replace', launcher)
            self.assertLess(launcher.index('"$BFSB_CHECKUP" --replace'), launcher.index("start_searxng_async"))
            self.assertNotIn("reset_stale_searxng", launcher)
            self.assertNotIn("stop_sarxng", launcher)
            self.assertNotIn("pkill -KILL -f '[b]fsb.main'", launcher)
            self.assertIn("BFSB_SEARXNG_OWNER_FILE", launcher)
            self.assertIn('current_owner" = "$BFSB_LAUNCHER_ID"', launcher)
            self.assertIn("claim_launcher_lock", launcher)
            self.assertIn("BFSB_CLEANUP_SERVICES", launcher)
            self.assertIn("shutdown_handler", launcher)
            self.assertIn("browser did not exit cleanly", launcher)
            self.assertIn("9>&-", launcher)
        legacy_launcher = (ROOT / "launch.sh").read_text(encoding="utf-8")
        self.assertIn('"$SCRIPT_DIR/bfsb_checkup.sh" --replace', legacy_launcher)


