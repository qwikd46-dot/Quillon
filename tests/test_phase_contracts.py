from pathlib import Path


ROOT = Path(__file__).parents[1]


class AddressBarNavigationContractTests(unittest.TestCase):
    """A typed domain must never depend on the silent bfsb:// action channel."""

    def setUp(self):
        self.template = (ROOT / "bfsb/templates/bfsb_combined.html").read_text(encoding="utf-8")
        self.server = (ROOT / "bfsb/core/server.py").read_text(encoding="utf-8")

    def test_address_bar_has_a_direct_navigation_fallback(self):
        self.assertIn("function navigateFromAddressBar", self.template)
        self.assertIn("window.location.replace(url)", self.template)
        self.assertIn("navigateFromAddressBar(direct)", self.template)

    def test_action_failures_are_logged_not_swallowed(self):
        self.assertNotIn("fetch(url).catch(function() {});", self.template)
        self.assertIn("action channel failed", self.template)

    def test_nav_buttons_prefer_local_http_routes(self):
        for route in ("/_bfsb/reload", "/_bfsb/goBack", "/_bfsb/goForward"):
            self.assertIn(route, self.template)
            self.assertIn(route, self.server)
        self.assertIn("function httpNavAction", self.template)

    def test_new_tab_rejects_non_http_schemes(self):
        self.assertIn("main._safe_action_target(url)", self.server)
        self.assertIn("main._safe_action_target(target)", self.server)


